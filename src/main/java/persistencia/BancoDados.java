package persistencia;

import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.SQLException;

public class BancoDados {
    private final String url;

    public BancoDados(String url) {
        this.url = url;
    }

    public Connection conectar() throws SQLException {
        return DriverManager.getConnection(url, "sa", "");
    }

    public void inicializar() throws SQLException {
        String sqlMedicao = """
        CREATE TABLE IF NOT EXISTS medicao (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            sensor_id VARCHAR NOT NULL,
            data_hora TIMESTAMP NOT NULL,
            valor DOUBLE PRECISION NOT NULL
        )
        """;

        String sqlAlerta = """
        CREATE TABLE IF NOT EXISTS alerta (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            sensor_id VARCHAR NOT NULL,
            valor_previsto DOUBLE PRECISION NOT NULL,
            limiar_atingido DOUBLE PRECISION NOT NULL,
            nivel VARCHAR NOT NULL,
            data_hora_emissao TIMESTAMP(9) NOT NULL
        )
        """;

        try (var conexao = conectar();
             var comandoMedicao = conexao.prepareStatement(sqlMedicao);
             var comandoAlerta = conexao.prepareStatement(sqlAlerta)) {
            comandoMedicao.executeUpdate();
            comandoAlerta.executeUpdate();
        }
    }
}